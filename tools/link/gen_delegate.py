#!/usr/bin/env python3
"""Generate apps/link/src/LinkDelegate.h from the controller's MainDelegate.

The controller's components take a MainDelegate and call a handful of its
methods; the interface itself has well over a hundred. The link program has
nothing behind most of them, so its delegate answers each one by doing
nothing. Generated rather than written, so that a method added to the
interface cannot be forgotten here: re-run this when MainDelegate.h changes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "apps/controller/src/Delegates/MainDelegate.h"
TARGET = ROOT / "apps/link/src/LinkDelegate.h"

text = SOURCE.read_text()
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
text = re.sub(r"//[^\n]*", "", text)

decls = re.findall(r"virtual\s+(.*?)\s*=\s*0\s*;", text, flags=re.S)


def default_for(ret):
    ret = ret.strip()
    if ret == "void":
        return None
    if ret == "bool":
        return "false"
    if ret.startswith("const char"):
        return '""'
    if "*" in ret:
        return "nullptr"
    return "0"


out = []
out.append("/*")
out.append("* Electra One MIDI Controller Firmware")
out.append("* See COPYRIGHT file at the top of the source tree.")
out.append("*")
out.append("* Generated by tools/link/gen_delegate.py from MainDelegate.h.")
out.append("* Do not edit; re-run the generator.")
out.append("*/")
out.append("")
out.append("/**")
out.append(" * @file LinkDelegate.h")
out.append(" *")
out.append(" * @brief The controller's delegate interface, answered by doing nothing.")
out.append(" *")
out.append(" * The control components are built for a controller and ask their")
out.append(" * delegate for things an Electra Link does not have: a detail window, a")
out.append(" * default value, a preset to reload. Every request lands here and is")
out.append(" * declined. The one thing the components need to work - a value moving")
out.append(" * on the screen - never goes through the delegate at all.")
out.append(" */")
out.append("")
out.append("#pragma once")
out.append("")
out.append('#include "MainDelegate.h"')
out.append("")
out.append("class LinkDelegate : public MainDelegate")
out.append("{")
out.append("public:")
out.append("    LinkDelegate() = default;")
out.append("    virtual ~LinkDelegate() = default;")
out.append("")

for decl in decls:
    decl = " ".join(decl.split())
    m = re.match(r"(.*?)\s*\b(\w+)\s*\((.*)\)\s*(const)?$", decl)
    if not m:
        sys.exit("cannot parse: " + decl)
    ret, name, args, const = m.groups()
    ret = ret.strip()
    if ret.endswith("*"):
        ret_type = ret
    else:
        ret_type = ret
    # unused-parameter attributes
    params = []
    for a in [x.strip() for x in args.split(",")] if args.strip() and args.strip() != "void" else []:
        params.append("[[maybe_unused]] " + a)
    sig = "    %s %s(%s)%s override" % (
        ret_type, name, ", ".join(params) if params else "void", " const" if const else "")
    dflt = default_for(ret_type.replace("*", "").strip() if "*" not in ret_type else ret_type)
    if dflt is None:
        out.append(sig)
        out.append("    {")
        out.append("    }")
    else:
        out.append(sig)
        out.append("    {")
        out.append("        return (%s);" % dflt)
        out.append("    }")
    out.append("")

out.append("};")
TARGET.write_text("\n".join(out) + "\n")
print("wrote %s: %d methods" % (TARGET.relative_to(ROOT), len(decls)))
